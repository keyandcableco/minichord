# The updater put into the switch-test app (pre: script of env:switch_test). From the updater's own build
# (.pio/build/updater: build it first, as build.sh does) it writes $BUILD_DIR/generated/updater_blob.h:
#   updater_image      the updater's bytes from 0x601E1000, FF-padded to whole pages, PROGMEM
#   updater_boot_page  the first page of sector 1 that points the switch at it: the IVT (as the core's
#                      bootdata.c writes it, with ResetHandler's address in the slot as the entry and no
#                      code signing data) and its boot data, then FF
#   UPDATER_LENGTH, UPDATER_ENTRY, UPDATER_CRC
# Every byte of the updater must land in its slot, or the build fails; so does an updater older than its
# sources. The header is rewritten only when it changes, so an unchanged updater doesn't rebuild the app.
import os
import struct
import subprocess
import zlib
Import("env")

FLASH = 0x60000000
SWITCH = 0x60001000
BOOT_DATA = SWITCH + 0x20
SLOT = 0x601E1000
SLOT_SIZE = 0x6000
PAGE = 256
IMAGE_END = 0x601E8000   # what the boot data says the image covers: up to the end of the saved copy

project = env.subst("$PROJECT_DIR")
updater = os.path.join(project, ".pio", "build", "updater")
hex_path = os.path.join(updater, "firmware.hex")
elf_path = os.path.join(updater, "firmware.elf")


def fail(problem):
    print("embed_updater: ERROR: " + problem)
    env.Exit(1)


def newest_source():
    paths = [os.path.join(project, "updater.ld"), os.path.join(project, "platformio.ini")]
    for folder in ("src/updater", "include"):
        for root, _, files in os.walk(os.path.join(project, folder)):
            paths += [os.path.join(root, f) for f in files]
    return max(os.path.getmtime(p) for p in paths)


def read_hex(path):
    data, base = {}, 0
    for number, line in enumerate(open(path), 1):
        line = line.strip()
        if not line:
            continue
        if not line.startswith(":"):
            fail("%s line %d isn't Intel HEX" % (path, number))
        raw = bytes.fromhex(line[1:])
        if sum(raw) & 0xFF:
            fail("%s line %d: bad checksum" % (path, number))
        count, offset, kind = raw[0], (raw[1] << 8) | raw[2], raw[3]
        if kind == 0:
            for i in range(count):
                data[base + offset + i] = raw[4 + i]
        elif kind == 4:
            base = ((raw[4] << 8) | raw[5]) << 16
        elif kind == 1:
            break
        elif kind != 5:   # 5: the start address, which the IVT gives instead
            fail("%s line %d: record type %d" % (path, number, kind))
    return data


def symbol(name):
    nm = os.path.join(env.PioPlatform().get_package_dir("toolchain-gccarmnoneeabi-teensy"), "bin", "arm-none-eabi-nm")
    for line in subprocess.run([nm, elf_path], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] == name:
            return int(parts[0], 16)
    fail("no %s in %s" % (name, elf_path))


if env.IsCleanTarget():   # `pio run -t clean` reads this script too, with no updater to embed
    Return()
if not os.path.exists(hex_path) or not os.path.exists(elf_path):
    fail("no updater build: run `pio run -e updater` first (build.sh does both)")
if os.path.getmtime(hex_path) < newest_source():
    fail("the updater's build is older than its sources: run `pio run -e updater` first (build.sh does both)")

data = read_hex(hex_path)
outside = [a for a in data if not SLOT <= a < SLOT + SLOT_SIZE]
if outside:
    fail("%d bytes of the updater outside its slot, the first at 0x%08X" % (len(outside), min(outside)))
end = max(data) + 1
length = (end - SLOT + PAGE - 1) // PAGE * PAGE
image = bytearray(b"\xff" * length)
for a, v in data.items():
    image[a - SLOT] = v

entry = symbol("ResetHandler") | 1   # a Thumb function's address, as (uint32_t)&ResetHandler is in bootdata.c
if not SLOT <= entry < SLOT + SLOT_SIZE:
    fail("ResetHandler at 0x%08X, outside the slot" % entry)

ivt = struct.pack("<8I", 0x432000D1, entry, 0, 0, BOOT_DATA, SWITCH, 0, 0)
boot_data = struct.pack("<3I", FLASH, IMAGE_END - FLASH, 0)
page = ivt + boot_data + b"\xff" * (PAGE - len(ivt) - len(boot_data))


def array(name, raw, progmem):
    lines = ["  " + ", ".join("0x%02X" % b for b in raw[i:i + 16]) + "," for i in range(0, len(raw), 16)]
    return "%sstatic const uint8_t %s[%d] __attribute__((aligned(4))) = {\n%s\n};\n" % (
        "PROGMEM " if progmem else "", name, len(raw), "\n".join(lines))


text = ("// Generated by scripts/embed_updater.py from the updater's build: don't edit\n#pragma once\n"
        "#define UPDATER_LENGTH %d\n#define UPDATER_ENTRY 0x%08X\n#define UPDATER_CRC 0x%08X\n\n" % (length, entry, zlib.crc32(image))
        + array("updater_image", image, True) + "\n" + array("updater_boot_page", page, False))

folder = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(folder, exist_ok=True)
out = os.path.join(folder, "updater_blob.h")
if not os.path.exists(out) or open(out).read() != text:
    open(out, "w").write(text)
env.Append(CPPPATH=[folder])
print("embed_updater: updater %d bytes (%d of the slot's %d), entry 0x%08X" % (end - SLOT, length, SLOT_SIZE, entry))
